CREATE OR REPLACE VIEW "public"."prediction_feedback_summary" AS
 SELECT "p"."id" AS "prediction_id",
    "p"."restaurant_id",
    "p"."service_date",
    "p"."service_type",
    "p"."predicted_covers",
    "p"."confidence",
    "p"."range_low",
    "p"."range_high",
    "p"."estimated_mape",
    "p"."created_at" AS "prediction_created_at",
    "pre"."id" AS "pre_feedback_id",
    "pre"."pre_validation",
    "pre"."pre_reasons",
    "pre"."pre_adjusted_covers",
    "pre"."created_at" AS "pre_feedback_created_at",
    "post"."id" AS "post_feedback_id",
    "post"."actual_covers",
    "post"."staff_foh_used",
    "post"."staff_boh_used",
    "post"."staff_rating",
    "post"."accuracy_pct",
    "post"."within_range",
    "post"."notes",
    "post"."created_at" AS "post_feedback_created_at"
   FROM (("public"."predictions" "p"
     LEFT JOIN "public"."user_feedback" "pre" ON ((("p"."id" = "pre"."prediction_id") AND (("pre"."feedback_type")::"text" = 'pre_service'::"text"))))
     LEFT JOIN "public"."user_feedback" "post" ON ((("p"."id" = "post"."prediction_id") AND (("post"."feedback_type")::"text" = 'post_service'::"text"))))
  ORDER BY "p"."service_date" DESC, "p"."created_at" DESC;


ALTER VIEW "public"."prediction_feedback_summary" OWNER TO "postgres";



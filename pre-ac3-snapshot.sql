CREATE OR REPLACE FUNCTION "public"."calculate_feedback_accuracy"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
DECLARE
    pred RECORD;
BEGIN
    -- Seulement pour post-service avec actual_covers
    IF NEW.feedback_type = 'post_service' AND NEW.actual_covers IS NOT NULL THEN
        -- Récupérer la prédiction associée
        SELECT predicted_covers, range_low, range_high
        INTO pred
        FROM predictions
        WHERE id = NEW.prediction_id;
        
        IF FOUND THEN
            -- Calculer accuracy_pct (erreur absolue en %)
            NEW.accuracy_pct := ABS(NEW.actual_covers - pred.predicted_covers)::NUMERIC / NULLIF(NEW.actual_covers, 0) * 100;
            
            -- Vérifier si dans l'intervalle
            NEW.within_range := (NEW.actual_covers >= pred.range_low AND NEW.actual_covers <= pred.range_high);
        END IF;
    END IF;
    
    RETURN NEW;
END;
$$;


